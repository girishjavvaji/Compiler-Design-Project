import React from 'react';
import { BarChart, Bar, XAxis, YAxis, Tooltip, ResponsiveContainer, Cell } from 'recharts';
import { LexicalMetrics } from '../../types/analyzer';

interface Props {
  lexical: LexicalMetrics;
}

const BAR_COLORS = ['#38BDF8', '#818CF8', '#F59E0B', '#10B981', '#EC4899', '#94A3B8'];

export const TokenDistributionChart: React.FC<Props> = ({ lexical }) => {
  const data = [
    { name: 'Keywords', count: lexical.keywordOccurrences, unique: lexical.uniqueKeywords },
    { name: 'Identifiers', count: lexical.identifierOccurrences, unique: lexical.uniqueIdentifiers },
    { name: 'Operators', count: lexical.operatorOccurrences, unique: lexical.uniqueOperators },
    { name: 'Operands', count: lexical.operandOccurrences, unique: lexical.uniqueOperands },
    {
      name: 'Literals',
      count:
        (lexical.tokenTypeCounts.NUMBER_LITERAL || 0) +
        (lexical.tokenTypeCounts.STRING_LITERAL || 0) +
        (lexical.tokenTypeCounts.CHAR_LITERAL || 0),
      unique: '-'
    },
    { name: 'Punctuation', count: lexical.tokenTypeCounts.PUNCTUATION || 0, unique: '-' }
  ];

  return (
    <div className="bg-navy-900 border border-navy-700/60 rounded-xl p-5 flex flex-col h-full shadow-lg">
      <div className="flex items-center justify-between mb-2">
        <h3 className="text-sm font-semibold text-slate-200">Token Categorization</h3>
        <span className="text-xs text-slate-400 bg-navy-800 px-2 py-0.5 rounded border border-navy-700 font-mono">
          {lexical.totalTokens} Tokens
        </span>
      </div>
      <p className="text-xs text-slate-400 mb-4">
        Lexical token frequencies generated by the lexical analysis DFA scanner.
      </p>

      <div className="h-64 w-full">
        <ResponsiveContainer width="100%" height="100%">
          <BarChart data={data} margin={{ top: 10, right: 10, left: -20, bottom: 20 }}>
            <XAxis
              dataKey="name"
              stroke="#64748B"
              fontSize={11}
              tickLine={false}
              interval={0}
              angle={-20}
              textAnchor="end"
            />
            <YAxis stroke="#64748B" fontSize={11} tickLine={false} />
            <Tooltip
              content={({ active, payload }) => {
                if (active && payload && payload.length) {
                  const item = payload[0].payload;
                  return (
                    <div className="bg-navy-950 border border-navy-700 p-2.5 rounded-lg shadow-xl text-xs">
                      <p className="font-semibold text-slate-200">{item.name}</p>
                      <p className="text-cyan-400 font-mono mt-1">Total Occurrences: {item.count}</p>
                      {item.unique !== '-' && (
                        <p className="text-indigo-400 font-mono">Unique Distinct: {item.unique}</p>
                      )}
                    </div>
                  );
                }
                return null;
              }}
            />
            <Bar dataKey="count" radius={[4, 4, 0, 0]}>
              {data.map((_, index) => (
                <Cell key={`cell-${index}`} fill={BAR_COLORS[index % BAR_COLORS.length]} />
              ))}
            </Bar>
          </BarChart>
        </ResponsiveContainer>
      </div>

      <div className="flex items-center justify-between text-xs text-slate-400 pt-3 border-t border-navy-800">
        <span>Unique Keywords: <strong className="text-cyan-400">{lexical.uniqueKeywords}</strong></span>
        <span>Unique Identifiers: <strong className="text-indigo-400">{lexical.uniqueIdentifiers}</strong></span>
        <span>Unique Operators: <strong className="text-amber-400">{lexical.uniqueOperators}</strong></span>
      </div>
    </div>
  );
};
